// Bundling a project's videos with the kit. The kit's Root imports the project's registry as
// "@lyceum/videos", and a few libraries must be single copies across the kit and the project's scenes
// (two Reacts break hooks; two Remotions break the scene context). Both are aliases in Remotion's
// webpack config, used by render and stills here and by Studio through a generated config file.

import { bundle } from "@remotion/bundler";
import { mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { CACHE, ENGINE, ENTRY, REGISTRY, ROOT, preparePublic } from "./paths.mjs";

const SINGLETONS = ["react", "react-dom", "remotion"];

/** Where a package lives: the project's copy if it has one, else the one beside Lyceum. */
function packageDir(name) {
  for (const base of [join(ROOT, "package.json"), join(ENGINE, "package.json")]) {
    try {
      return dirname(createRequire(base).resolve(`${name}/package.json`));
    } catch {}
  }
  throw new Error(`cannot find ${name} from ${ROOT} or ${ENGINE}`);
}

/** The aliases every bundle of a project needs. */
export function aliases() {
  return { "@lyceum/videos": REGISTRY, ...Object.fromEntries(SINGLETONS.map((name) => [name, packageDir(name)])) };
}

/** Adds the aliases to a Remotion webpack config. */
export function webpackOverride(config) {
  return { ...config, resolve: { ...config.resolve, alias: { ...(config.resolve?.alias ?? {}), ...aliases() } } };
}

/** Bundles the project for rendering and returns the serve URL. */
export function bundleProject() {
  return bundle({ entryPoint: ENTRY, publicDir: preparePublic(), webpackOverride });
}

/** Writes a Remotion config for Studio carrying the same aliases, and returns its path. */
export function studioConfig() {
  // The file lives in the project's cache, so the bare "@remotion/cli/config" resolves to the same
  // module instance the CLI uses; an absolute path would be bundled as a separate copy and ignored.
  const file = join(CACHE, "remotion.config.ts");
  mkdirSync(CACHE, { recursive: true });
  writeFileSync(
    file,
    `// Generated by \`lyceum studio\`; regenerated on every run.
import { Config } from "@remotion/cli/config";

const alias = ${JSON.stringify(aliases(), null, 2)};
Config.overrideWebpackConfig((config) => ({
  ...config,
  resolve: { ...config.resolve, alias: { ...(config.resolve?.alias ?? {}), ...alias } },
}));
Config.setVideoImageFormat("jpeg");
Config.setJpegQuality(92);
Config.setCodec("h264");
Config.setCrf(16);
`,
  );
  return file;
}
